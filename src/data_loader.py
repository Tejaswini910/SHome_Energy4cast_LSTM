"""
data_loader.py
==============
Data Ingestion Module.

Responsible for:
    - Loading the UCI "Individual Household Electric Power Consumption"
      dataset (or any compatible CSV).
    - Parsing datetime information correctly.
    - Handling missing values ('?' markers, NaNs, gaps).
    - Resampling the data to a consistent frequency (default 15 minutes).
    - Sorting data chronologically.
    - Providing a synthetic data generator as a fallback so the app is
      fully runnable (demo mode) even without the full ~20MB UCI archive.

Output: a clean, chronologically sorted pandas DataFrame indexed by
`Datetime` with a numeric `Global_active_power` column (kW), ready for
EDA and sequence modelling.
"""

from __future__ import annotations

import os

import numpy as np
import pandas as pd

TARGET_COL = "Global_active_power"


def _standardize_columns(df: pd.DataFrame) -> pd.DataFrame:
    """Normalize column names so downstream code can rely on them."""
    df = df.copy()
    df.columns = [c.strip() for c in df.columns]
    return df


def load_raw_uci_dataset(path: str) -> pd.DataFrame:
    """
    Load the original UCI dataset format:
        Date;Time;Global_active_power;Global_reactive_power;Voltage;
        Global_intensity;Sub_metering_1;Sub_metering_2;Sub_metering_3

    Missing values in the raw file are marked with '?'.
    """
    df = pd.read_csv(
        path,
        sep=";",
        na_values=["?", "", "NA", "nan"],
        low_memory=False,
    )
    df = _standardize_columns(df)

    datetime_str = df["Date"].astype(str) + " " + df["Time"].astype(str)
    df["Datetime"] = pd.to_datetime(datetime_str, format="%d/%m/%Y %H:%M:%S", errors="coerce")
    df = df.drop(columns=["Date", "Time"])

    numeric_cols = [
        "Global_active_power",
        "Global_reactive_power",
        "Voltage",
        "Global_intensity",
        "Sub_metering_1",
        "Sub_metering_2",
        "Sub_metering_3",
    ]
    for col in numeric_cols:
        if col in df.columns:
            df[col] = pd.to_numeric(df[col], errors="coerce")

    return df


def load_simple_dataset(path: str) -> pd.DataFrame:
    """
    Load a pre-processed/simplified dataset with a `Datetime` column and a
    `Global_active_power` column (the format used for the bundled sample
    dataset generated by `scripts/generate_sample_data.py`).
    """
    df = pd.read_csv(path, na_values=["?", "", "NA", "nan"])
    df = _standardize_columns(df)
    df["Datetime"] = pd.to_datetime(df["Datetime"], errors="coerce")
    if TARGET_COL in df.columns:
        df[TARGET_COL] = pd.to_numeric(df[TARGET_COL], errors="coerce")
    return df


def generate_synthetic_data(
    start: str = "2024-01-01",
    days: int = 60,
    freq: str = "15min",
    seed: int = 42,
) -> pd.DataFrame:
    """
    Generate a realistic synthetic household power consumption series.

    Combines a daily seasonal pattern (low at night, peaks at morning and
    evening), a weekly pattern (higher usage on weekends), slow seasonal
    drift, and random noise/appliance spikes. Used as a safe fallback for
    demos and for Streamlit Community Cloud deployments where the full
    UCI archive is not bundled.
    """
    rng = np.random.default_rng(seed)
    periods = int(days * 24 * 60 / 15)
    idx = pd.date_range(start=start, periods=periods, freq=freq)

    hour = idx.hour + idx.minute / 60.0
    day_of_week = idx.dayofweek

    # Base daily load curve: night low, morning + evening peaks.
    daily_pattern = (
        0.6
        + 0.5 * np.exp(-((hour - 8) ** 2) / 8)   # morning peak
        + 0.9 * np.exp(-((hour - 19.5) ** 2) / 6)  # evening peak
        + 0.15 * np.sin(2 * np.pi * hour / 24)
    )

    weekend_boost = np.where(day_of_week >= 5, 1.15, 1.0)
    seasonal_drift = 1.0 + 0.05 * np.sin(2 * np.pi * np.arange(periods) / (periods / 2))

    noise = rng.normal(0, 0.12, size=periods)
    spikes = rng.choice([0, 0, 0, 0, 0, 1], size=periods) * rng.uniform(0.5, 1.5, size=periods)

    power = daily_pattern * weekend_boost * seasonal_drift + noise + spikes
    power = np.clip(power, 0.05, None)

    df = pd.DataFrame({"Datetime": idx, TARGET_COL: power})
    return df


def handle_missing_values(df: pd.DataFrame, target_col: str = TARGET_COL) -> pd.DataFrame:
    """Interpolate short gaps and forward/backward-fill remaining edges."""
    df = df.copy()
    df = df.dropna(subset=["Datetime"])
    df = df.set_index("Datetime")
    numeric_df = df.select_dtypes(include=[np.number])
    numeric_df = numeric_df.interpolate(method="time").ffill().bfill()
    df[numeric_df.columns] = numeric_df
    df = df.dropna(subset=[target_col])
    return df.reset_index()


def resample_data(df: pd.DataFrame, freq: str = "15min", target_col: str = TARGET_COL) -> pd.DataFrame:
    """Resample to a uniform frequency, averaging within each bucket."""
    df = df.set_index("Datetime").sort_index()
    numeric_df = df.select_dtypes(include=[np.number])
    resampled = numeric_df.resample(freq).mean()
    resampled[target_col] = resampled[target_col].interpolate(method="time").ffill().bfill()
    return resampled.reset_index()


def load_data(
    path: str | None = None,
    freq: str = "15min",
    fallback_to_synthetic: bool = True,
) -> pd.DataFrame:
    """
    Full ingestion pipeline: load -> parse datetime -> handle missing
    values -> resample -> sort chronologically.

    Returns a clean DataFrame with columns: ["Datetime", "Global_active_power", ...]
    sorted ascending by Datetime.
    """
    df: pd.DataFrame | None = None

    if path and os.path.exists(path):
        try:
            # Try the simplified format first (Datetime, Global_active_power, ...).
            df = load_simple_dataset(path)
            if "Datetime" not in df.columns or df["Datetime"].isna().all():
                raise ValueError("Simple format parse failed")
        except Exception:
            try:
                df = load_raw_uci_dataset(path)
            except Exception:
                df = None

    if df is None or df.empty:
        if not fallback_to_synthetic:
            raise FileNotFoundError(f"Dataset not found at: {path}")
        df = generate_synthetic_data(freq=freq)

    df = handle_missing_values(df)
    df = resample_data(df, freq=freq)
    df = df.sort_values("Datetime").reset_index(drop=True)
    return df
